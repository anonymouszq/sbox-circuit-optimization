  wire n18 = x[2] ^ n17;
  wire n19 = n12 ^ n18;
  wire n20 = ~(n15 ^ n19);
  wire n21 = ~(n2 & n5);
  wire n22 = n8 ^ n21;
  wire n23 = ~(n5 & n11);
  wire n24 = ~(n19 ^ n23);

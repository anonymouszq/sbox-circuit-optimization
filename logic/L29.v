  wire n26 = ~(x[0] & n25);
  wire n27 = n17 ^ n26;
  wire n28 = n15 ^ n27;
  wire n29 = n23 ^ n28;
  wire n30 = x[4] ^ n10;
  wire n31 = ~(x[1] ^ n0);
  wire n32 = ~(n30 & n31);
  wire n33 = n4 ^ n32;
  wire n34 = n22 ^ n33;
  assign y[0] = n14;
  assign y[1] = n20;
